import scipy.stats as stats
import pandas as pd



archivo = "REGISTRODATOS_P3_TETECHOSLADERAN_S (1).xlsx"

norte = pd.read_excel(
    archivo,
    sheet_name="LADERA N",
    header=3
)

sur = pd.read_excel(
    archivo,
    sheet_name="LADERA S",
    header=3
)

columnas = {
    "ID Tetecho": "ID",
    "Diametro basal (cm)": "Diametro_basal",
    "Ramificaciónes N": "Ramas_norte",
    "Ramificaciónes S": "Ramas_sur"
}

norte = norte.rename(columns=columnas)
sur = sur.rename(columns=columnas)


norte["Ladera"] = "Norte"
sur["Ladera"] = "Sur"


datos = pd.concat([norte, sur], ignore_index=True)

# Convertir columnas a valores numéricos
for columna in ["Diametro_basal", "Ramas_norte", "Ramas_sur"]:
    datos[columna] = pd.to_numeric(datos[columna], errors="coerce")

# Eliminar registros sin datos necesarios
datos = datos.dropna(
    subset=["Diametro_basal", "Ramas_norte", "Ramas_sur"]
)

# Calcular total de ramas por tetecho
datos["Total_ramas"] = (
    datos["Ramas_norte"] + datos["Ramas_sur"]
)

# Separar nuevamente por ladera
norte = datos[datos["Ladera"] == "Norte"]
sur = datos[datos["Ladera"] == "Sur"]

print("DATOS CARGADOS CORRECTAMENTE")
print(datos.head())

print("\nTotal de registros:", len(datos))
print("Registros ladera norte:", len(norte))
print("Registros ladera sur:", len(sur))

# 5. MANN-WHITNEY

U, p_mann = stats.mannwhitneyu(
    norte["Total_ramas"],
    sur["Total_ramas"],
    alternative="two-sided"
)

# 6. SPEARMAN GENERAL
rho_general, p_general = stats.spearmanr(
    datos["Diametro_basal"],
    datos["Total_ramas"]
)

# 7. SPEARMAN POR LADERA


rho_norte, p_norte = stats.spearmanr(
    norte["Diametro_basal"],
    norte["Total_ramas"]
)

rho_sur, p_sur = stats.spearmanr(
    sur["Diametro_basal"],
    sur["Total_ramas"]
)

# 8. CHI-CUADRADA EXPLORATORIA

tabla = [
    [norte["Ramas_norte"].sum(), norte["Ramas_sur"].sum()],
    [sur["Ramas_norte"].sum(), sur["Ramas_sur"].sum()]
]

chi2, p_chi, gl, esperados = stats.chi2_contingency(tabla)

# 9. MOSTRAR RESULTADOS

print("\n========== MANN-WHITNEY ==========")
print("U:", U)
print("p:", p_mann)

print("\n========== SPEARMAN GENERAL ==========")
print("Rho:", rho_general)
print("p:", p_general)

print("\n========== SPEARMAN LADERA NORTE ==========")
print("Rho:", rho_norte)
print("p:", p_norte)

print("\n========== SPEARMAN LADERA SUR ==========")
print("Rho:", rho_sur)
print("p:", p_sur)

print("\n========== CHI-CUADRADA ==========")
print("Chi2:", chi2)
print("p:", p_chi)
print("Grados de libertad:", gl)
print("Frecuencias esperadas:")
print(esperados)

